function beatPatternToNotes(pattern, channel, config) {
  const beatSec = 60 / config.bpm;

  return pattern.map((entry) => ({
    channel,
    start: entry.beat * beatSec,
    duration: entry.beats * beatSec * 0.92,
    pitch: entry.pitch,
  }));
}

function beatDrumsToNotes(pattern, config) {
  const beatSec = 60 / config.bpm;

  return pattern.map((entry) => ({
    channel: 'drum',
    start: entry.beat * beatSec,
    duration: entry.kind === 'snare' ? beatSec * 0.14 : beatSec * 0.05,
    kind: entry.kind,
  }));
}

export function buildSockMonsterBattleMusicScore(
  config = SOCK_MONSTER_BATTLE_MUSIC_CONFIG,
) {
  return {
    config,
    notes: [
      ...beatPatternToNotes(SOCK_MONSTER_BATTLE_ORGAN, 'organ', config),
      ...beatPatternToNotes(SOCK_MONSTER_BATTLE_ARP, 'arp', config),
      ...beatPatternToNotes(SOCK_MONSTER_BATTLE_BASS, 'bass', config),
      ...beatDrumsToNotes(SOCK_MONSTER_BATTLE_DRUMS, config),
    ],
  };
}
