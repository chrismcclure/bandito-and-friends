function beatPatternToNotes(pattern, channel, config) {
  const beatSec = 60 / config.bpm;

  return pattern.map((entry) => ({
    channel,
    start: entry.beat * beatSec,
    duration: entry.beats * beatSec * 0.92,
    pitch: entry.pitch,
  }));
}

function beatDrumsToNotes(pattern, config) {
  const beatSec = 60 / config.bpm;

  return pattern.map((entry) => ({
    channel: 'drum',
    start: entry.beat * beatSec,
    duration: entry.kind === 'snare' ? beatSec * 0.12 : beatSec * 0.06,
    kind: entry.kind,
  }));
}

export function buildBossBattleMusicScore(config = BOSS_BATTLE_MUSIC_CONFIG) {
  return {
    config,
    notes: [
      ...beatPatternToNotes(BOSS_BATTLE_MELODY1, 'melody1', config),
      ...beatPatternToNotes(BOSS_BATTLE_MELODY2, 'melody2', config),
      ...beatPatternToNotes(BOSS_BATTLE_BASS, 'bass', config),
      ...beatDrumsToNotes(BOSS_BATTLE_DRUMS, config),
    ],
  };
}
